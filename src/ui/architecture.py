def _load_image() -> bytes | None:
    """Прочитать файл схемы архитектуры."""

    try:
        return ARCHITECTURE_IMAGE.read_bytes()
    except OSError:
        return None


def render() -> None:
    page_header("Моделирование архитектуры квантового компьютера")

    st.markdown(
        "Приложение показывает **обобщённую функциональную модель** квантового "
        "вычислительного комплекса: как пользовательская схема превращается в "
        "последовательность операций, как моделируется состояние регистра, "
        "как выполняется измерение и как классическая часть обрабатывает "
        "результаты. Модель ошибок встроена в исполнение вентилей и в "
        "считывание — именно там находятся основные источники аппаратных "
        "ошибок."
    )

    options = ["all", "noise"] + [key for key, _, _ in ARCHITECTURE_BLOCKS]
    labels = {
        "all": "Все блоки",
        "noise": "Модель аппаратных ошибок",
    }
    labels.update({key: title for key, title, _ in ARCHITECTURE_BLOCKS})

    image = _load_image()
    if image is None:
        st.warning(
            "Не найден файл схемы assets/architecture.png. "
            "Скопируйте каталог assets вместе с проектом."
        )
    else:
        st.image(image)

    selected = st.radio(
        "Показать подробнее о блоке",
        options=options,
        format_func=lambda value: labels[value],
        horizontal=True,
        key="arch_block",
    )

    if selected in BLOCK_DETAILS:
        st.info(f"**{labels[selected]}.** {BLOCK_DETAILS[selected]}")
    else:
        st.caption(
            "Выберите блок выше, чтобы увидеть его роль в модели. "
            "Номера в схеме соответствуют порядку обработки данных."
        )

    section("Блоки модели", "Назначение блоков и что они отображают.")
    table_rows = [
        {
            "№": index,
            "Блок": title,
            "Назначение в модели": subtitle,
            "Что отображается": BLOCK_DETAILS.get(key, ""),
        }
        for index, (key, title, subtitle) in enumerate(ARCHITECTURE_BLOCKS, start=1)
    ]
    st.dataframe(
        pd.DataFrame(table_rows),
        hide_index=True,
        column_config={
            "№": st.column_config.NumberColumn(width="small"),
            "Назначение в модели": st.column_config.TextColumn(width="medium"),
            "Что отображается": st.column_config.TextColumn(width="large"),
        },
    )

    section("Поток выполнения", "Что происходит после нажатия «Запустить».")
    st.markdown(
        "1. **Проверка схемы.** Ошибки объясняются обычным языком: например, "
        "у CNOT управляющий и целевой кубиты не могут совпадать.\n"
        "2. **Построение состояния.** Начальное состояние |00…0⟩ "
        "последовательно преобразуется матрицами вентилей.\n"
        "3. **Модель ошибок.** В режиме с ошибками для каждого измерения "
        "разыгрывается своя траектория: после вентилей к кубитам применяются "
        "случайные X или Z, при измерении — инверсии битов.\n"
        "4. **Измерение.** Для каждого из shots исходов разыгрывается "
        "битовая строка; частоты складываются в гистограмму.\n"
        "5. **Классическая обработка.** Считаются теоретические вероятности, "
        "TVD, вероятность целевого результата; результат можно сохранить.\n"
        "6. **Эксперименты.** Серия запусков при разных вероятностях ошибки "
        "или глубине схемы даёт таблицу и график с доверительными интервалами."
    )

    st.info(
        "**Важно про физическую реализацию.** В реальных квантовых компьютерах "
        "эти блоки выглядят по-разному: у сверхпроводящих кубитов — микроволновые "
        "резонаторы и импульсы, у ионов в ловушке — лазерные операции. "
        "Приложение показывает обобщённую функциональную модель и не является "
        "копией конкретного устройства; подключение к настоящему квантовому "
        "процессору не используется."
    )


